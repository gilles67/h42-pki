"""`h42pki scep …`: SCEP challenges (ADR-0019).

A challenge is generated by the server and printed once, alone on standard output; everything
else goes to standard error.
"""

from datetime import UTC, datetime
from typing import Annotated

import typer

from h42pki.cli._runtime import CLI_ACTOR, fail, print_table, run
from h42pki.config import Settings
from h42pki.models import CredentialStatus, EnrollmentCredential
from h42pki.services.scep_challenges import (
    MAX_EXPIRES_IN_HOURS,
    CreatedChallenge,
    ScepChallengeService,
    is_usable,
)

app = typer.Typer(help="SCEP enrollment (RFC 8894).", no_args_is_help=True)
challenge_app = typer.Typer(help="SCEP challenges (challengePassword).", no_args_is_help=True)
app.add_typer(challenge_app, name="challenge")

COLUMNS = ("ID", "STATUS", "USES", "EXPIRES", "DESCRIPTION")
IdArgument = Annotated[str, typer.Argument(metavar="ID", help="Challenge id (before the dash).")]


def _when(value: datetime | None) -> str:
    return value.isoformat(timespec="seconds") if value is not None else "-"


def _uses(credential: EnrollmentCredential) -> str:
    limit = "unlimited" if credential.max_uses is None else str(credential.max_uses)
    return f"{credential.use_count}/{limit}"


def _status(credential: EnrollmentCredential) -> str:
    if credential.status is CredentialStatus.DISABLED:
        return "disabled"
    return "usable" if is_usable(credential, datetime.now(UTC)) else "spent"


@challenge_app.command()
def create(
    reusable: Annotated[
        bool, typer.Option("--reusable", help="No limit of uses (a fleet of devices).")
    ] = False,
    max_uses: Annotated[int | None, typer.Option(min=1, help="Uses allowed (default 1).")] = None,
    expires_in_hours: Annotated[
        int | None, typer.Option(min=1, max=MAX_EXPIRES_IN_HOURS, help="Expiry, in hours.")
    ] = None,
    description: Annotated[str | None, typer.Option(help="Free text.")] = None,
) -> None:
    """Generate a challenge: single-use by default, valid for any enabled profile."""
    if reusable and max_uses is not None:
        fail("--reusable and --max-uses exclude each other", code=2)

    async def operation(settings: Settings) -> CreatedChallenge:
        return await ScepChallengeService().create(
            max_uses=None if reusable else (max_uses or 1),
            expires_in_hours=expires_in_hours,
            description=description,
            actor=CLI_ACTOR,
        )

    created = run(operation)
    typer.secho(
        f"SCEP challenge {created.credential.identifier} created ({_uses(created.credential)} "
        "uses), shown this one time:",
        fg="green",
        err=True,
    )
    typer.echo(created.challenge.text)


@challenge_app.command("list")
def list_challenges() -> None:
    """List the challenges (never their secret)."""

    async def operation(settings: Settings) -> list[EnrollmentCredential]:
        return await ScepChallengeService().list()

    print_table(
        COLUMNS,
        [
            (c.identifier, _status(c), _uses(c), _when(c.expires_at), c.description or "-")
            for c in run(operation)
        ],
    )


@challenge_app.command()
def show(challenge_id: IdArgument) -> None:
    """Show a challenge (never its secret)."""

    async def operation(settings: Settings) -> EnrollmentCredential:
        return await ScepChallengeService().get(challenge_id)

    credential = run(operation)
    rows = [
        ("ID", credential.identifier),
        ("Status", _status(credential)),
        ("Uses", _uses(credential)),
        ("Expires", _when(credential.expires_at)),
        ("Description", credential.description or "-"),
        ("Created", f"{_when(credential.created_at)} by {credential.created_by}"),
        ("Last used", _when(credential.last_used_at)),
    ]
    width = max(len(label) for label, _ in rows)
    for label, value in rows:
        typer.echo(f"{label.ljust(width)}  {value}")


def _set(challenge_id: str, status: CredentialStatus) -> None:
    async def operation(settings: Settings) -> EnrollmentCredential:
        return await ScepChallengeService().set_status(challenge_id, status, actor=CLI_ACTOR)

    credential = run(operation)
    typer.secho(f"SCEP challenge {credential.identifier} {credential.status.value}.", fg="green")


@challenge_app.command()
def disable(challenge_id: IdArgument) -> None:
    """Disable a challenge."""
    _set(challenge_id, CredentialStatus.DISABLED)


@challenge_app.command()
def enable(challenge_id: IdArgument) -> None:
    """Enable a challenge again."""
    _set(challenge_id, CredentialStatus.ACTIVE)


@challenge_app.command()
def delete(challenge_id: IdArgument) -> None:
    """Delete a challenge."""

    async def operation(settings: Settings) -> None:
        await ScepChallengeService().delete(challenge_id, actor=CLI_ACTOR)

    run(operation)
    typer.secho(f"SCEP challenge {challenge_id} deleted.", fg="green")
