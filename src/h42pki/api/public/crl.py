"""``GET /crl/{name}.crl``: the last stored CRL of a local CA (RFC 5280, plain HTTP).

Never signs anything: the CRL is generated by the revocation and the scheduled task, a request
from anyone only reads it (ADR-0017).
"""

import hashlib
from datetime import UTC, datetime

from fastapi import APIRouter, Request, Response

from h42pki.api.problems import PROBLEM_RESPONSES
from h42pki.api.public.cache import cacheable
from h42pki.services.crl import CrlService

CRL_MEDIA_TYPE = "application/pkix-crl"

router = APIRouter(prefix="/crl", tags=["public"], responses=PROBLEM_RESPONSES)


@router.get(
    "/{name}.crl",
    response_class=Response,
    responses={200: {"content": {CRL_MEDIA_TYPE: {}}}},
    summary="Current CRL of a local CA, DER (target of the CRL distribution points)",
)
async def crl_der(name: str, request: Request) -> Response:
    crl = await CrlService.published(name)
    # Cacheable until the next scheduled CRL; a revocation publishes a new one before that.
    seconds = max(0, int((crl.next_update - datetime.now(UTC)).total_seconds()))
    return cacheable(
        request,
        body=crl.der,
        media_type=CRL_MEDIA_TYPE,
        etag=f'"{hashlib.sha256(crl.der).hexdigest()}"',
        last_modified=crl.this_update,
        cache_control=f"public, max-age={seconds}",
    )
