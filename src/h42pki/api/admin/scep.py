"""``/api/v1/scep/challenges``: SCEP challenges, no authentication until the release (ADR-0008).

A challenge is generated by the server and returned once, in the answer that creates it.
"""

from datetime import UTC, datetime

from fastapi import APIRouter, Response, status
from pydantic import Field

from h42pki.api.admin.deps import Actor
from h42pki.api.admin.schemas import Schema
from h42pki.api.problems import PROBLEM_RESPONSES
from h42pki.models import CredentialStatus, EnrollmentCredential
from h42pki.services.scep_challenges import (
    MAX_EXPIRES_IN_HOURS,
    ScepChallengeService,
    is_usable,
)

router = APIRouter(prefix="/api/v1/scep/challenges", tags=["scep"], responses=PROBLEM_RESPONSES)


class ScepChallengeCreate(Schema):
    max_uses: int | None = Field(
        default=1, ge=1, description="Uses allowed: 1 by default; null for a reusable challenge."
    )
    expires_in_hours: int | None = Field(default=None, ge=1, le=MAX_EXPIRES_IN_HOURS)
    description: str | None = Field(default=None, max_length=255)


class ScepChallengeOut(Schema):
    id: str = Field(description="Public part of the challenge, before the dash.")
    status: CredentialStatus
    usable: bool = Field(description="Active, not expired and not exhausted.")
    max_uses: int | None = Field(description="null: reusable.")
    use_count: int
    expires_at: datetime | None
    description: str | None
    created_by: str
    created_at: datetime
    last_used_at: datetime | None

    @classmethod
    def from_model(cls, credential: EnrollmentCredential) -> "ScepChallengeOut":
        return cls(
            id=credential.identifier,
            status=credential.status,
            usable=is_usable(credential, datetime.now(UTC)),
            max_uses=credential.max_uses,
            use_count=credential.use_count,
            expires_at=credential.expires_at,
            description=credential.description,
            created_by=credential.created_by,
            created_at=credential.created_at,
            last_used_at=credential.last_used_at,
        )


class ScepChallengeCreated(Schema):
    challenge: str = Field(description="<id>-<secret>, shown this one time.")
    details: ScepChallengeOut


@router.post("", status_code=status.HTTP_201_CREATED)
async def create_challenge(body: ScepChallengeCreate, actor: Actor) -> ScepChallengeCreated:
    created = await ScepChallengeService().create(
        max_uses=body.max_uses,
        expires_in_hours=body.expires_in_hours,
        description=body.description,
        actor=actor,
    )
    return ScepChallengeCreated(
        challenge=created.challenge.text, details=ScepChallengeOut.from_model(created.credential)
    )


@router.get("")
async def list_challenges() -> list[ScepChallengeOut]:
    return [ScepChallengeOut.from_model(c) for c in await ScepChallengeService().list()]


@router.get("/{challenge_id}")
async def get_challenge(challenge_id: str) -> ScepChallengeOut:
    return ScepChallengeOut.from_model(await ScepChallengeService().get(challenge_id))


@router.post("/{challenge_id}/disable")
async def disable_challenge(challenge_id: str, actor: Actor) -> ScepChallengeOut:
    credential = await ScepChallengeService().set_status(
        challenge_id, CredentialStatus.DISABLED, actor=actor
    )
    return ScepChallengeOut.from_model(credential)


@router.post("/{challenge_id}/enable")
async def enable_challenge(challenge_id: str, actor: Actor) -> ScepChallengeOut:
    credential = await ScepChallengeService().set_status(
        challenge_id, CredentialStatus.ACTIVE, actor=actor
    )
    return ScepChallengeOut.from_model(credential)


@router.delete("/{challenge_id}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_challenge(challenge_id: str, actor: Actor) -> Response:
    await ScepChallengeService().delete(challenge_id, actor=actor)
    return Response(status_code=status.HTTP_204_NO_CONTENT)
