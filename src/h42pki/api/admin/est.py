"""``/api/v1/est/accounts``: EST accounts (HTTP Basic), no authentication before release (ADR-0008).

A password is never returned, except one generated by the server, shown once in the answer of
the request that created it.
"""

from datetime import datetime

from fastapi import APIRouter, Response, status
from pydantic import AwareDatetime, Field, SecretStr

from h42pki.api.admin.deps import Actor
from h42pki.api.admin.schemas import Schema
from h42pki.api.problems import PROBLEM_RESPONSES
from h42pki.models import CredentialStatus, EnrollmentCredential
from h42pki.services.est_accounts import AccountSecret, EstAccountService

router = APIRouter(prefix="/api/v1/est/accounts", tags=["est"], responses=PROBLEM_RESPONSES)


class EstAccountCreate(Schema):
    username: str = Field(description="1 to 64 letters, digits, dots, hyphens or underscores.")
    password: SecretStr | None = Field(
        default=None, description="8 to 1024 characters; generated and returned once if absent."
    )
    expires_at: AwareDatetime | None = None
    description: str | None = Field(default=None, max_length=255)


class EstPasswordChange(Schema):
    password: SecretStr | None = Field(
        default=None, description="New password; generated and returned once if absent."
    )


class EstAccountOut(Schema):
    username: str
    status: CredentialStatus
    expires_at: datetime | None
    description: str | None
    created_by: str
    created_at: datetime
    last_used_at: datetime | None

    @classmethod
    def from_model(cls, account: EnrollmentCredential) -> "EstAccountOut":
        return cls(
            username=account.identifier,
            status=account.status,
            expires_at=account.expires_at,
            description=account.description,
            created_by=account.created_by,
            created_at=account.created_at,
            last_used_at=account.last_used_at,
        )


class EstAccountSecretOut(Schema):
    account: EstAccountOut
    password: str | None = Field(
        description="The generated password, shown this one time; null when it was chosen."
    )

    @classmethod
    def from_secret(cls, secret: AccountSecret) -> "EstAccountSecretOut":
        return cls(
            account=EstAccountOut.from_model(secret.account), password=secret.generated_password
        )


def _secret(value: SecretStr | None) -> str | None:
    return value.get_secret_value() if value is not None else None


@router.post("", status_code=status.HTTP_201_CREATED)
async def create_account(body: EstAccountCreate, actor: Actor) -> EstAccountSecretOut:
    created = await EstAccountService().create(
        body.username,
        password=_secret(body.password),
        expires_at=body.expires_at,
        description=body.description,
        actor=actor,
    )
    return EstAccountSecretOut.from_secret(created)


@router.get("")
async def list_accounts() -> list[EstAccountOut]:
    return [EstAccountOut.from_model(account) for account in await EstAccountService().list()]


@router.get("/{username}")
async def get_account(username: str) -> EstAccountOut:
    return EstAccountOut.from_model(await EstAccountService().get(username))


@router.post("/{username}/disable")
async def disable_account(username: str, actor: Actor) -> EstAccountOut:
    account = await EstAccountService().set_status(username, CredentialStatus.DISABLED, actor=actor)
    return EstAccountOut.from_model(account)


@router.post("/{username}/enable")
async def enable_account(username: str, actor: Actor) -> EstAccountOut:
    account = await EstAccountService().set_status(username, CredentialStatus.ACTIVE, actor=actor)
    return EstAccountOut.from_model(account)


@router.post("/{username}/password")
async def change_password(
    username: str, body: EstPasswordChange, actor: Actor
) -> EstAccountSecretOut:
    changed = await EstAccountService().set_password(username, _secret(body.password), actor=actor)
    return EstAccountSecretOut.from_secret(changed)


@router.delete("/{username}", status_code=status.HTTP_204_NO_CONTENT)
async def delete_account(username: str, actor: Actor) -> Response:
    await EstAccountService().delete(username, actor=actor)
    return Response(status_code=status.HTTP_204_NO_CONTENT)
